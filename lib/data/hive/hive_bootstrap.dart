import 'package:hive_ce_flutter/hive_flutter.dart';

import '../../hive_registrar.g.dart';
import 'models/cached_lyrics_entry.dart';
import 'models/recent_song_entry.dart';

const String lyricsBoxName = 'lyrics_cache_v1';
const String recentSongsBoxName = 'recent_songs_v1';

class HiveBoxes {
  const HiveBoxes({required this.lyrics, required this.recentSongs});

  final Box<CachedLyricsEntry> lyrics;
  final Box<RecentSongEntry> recentSongs;
}

/// Initializes Hive and opens both boxes this app uses. Only the main engine
/// touches Hive — the overlay isolate never reads or writes it directly,
/// it only ever receives already-resolved lyrics via shareData from the
/// main engine — so there's no dual-isolate box-access story to manage
/// here, unlike a design where the overlay reads the box itself.
Future<HiveBoxes> initHive() async {
  await Hive.initFlutter();
  if (!Hive.isAdapterRegistered(0)) {
    Hive.registerAdapters(); // generated by hive_ce_generator — see hive_registrar.g.dart
  }
  final lyrics = await Hive.openBox<CachedLyricsEntry>(lyricsBoxName);
  final recentSongs = await Hive.openBox<RecentSongEntry>(recentSongsBoxName);
  return HiveBoxes(lyrics: lyrics, recentSongs: recentSongs);
}
